fn render_generated_typescript(decls: &[String]) -> String {
    let mut blocks = vec![
        "// Auto-generated by `cargo run -p qlevel-bridge --bin export_bindings`. Do not edit manually.".to_owned(),
        "// Fixed-point rust_decimal values cross Tauri IPC strictly as base-10 strings.".to_owned(),
        "export type DecimalValue = string;".to_owned(),
    ];

    for decl in decls {
        if decl.starts_with("export ") {
            blocks.push(decl.clone());
        } else {
            blocks.push(format!("export {decl}"));
        }
    }

    let mut joined = blocks.join("\n\n");
    joined.push('\n');
    joined
}

/// Extracts all identifier and string-literal contract tokens (`>= 2` chars) from TypeScript code.
fn extract_contract_tokens(ts_source: &str) -> BTreeSet<String> {
    let mut tokens = BTreeSet::new();
    let mut current = String::new();
    let mut in_line_comment = false;

    for ch in ts_source.chars() {
        if ch == '\n' {
            in_line_comment = false;
        }
        if in_line_comment {
            continue;
        }
        if ch.is_ascii_alphanumeric() || ch == '_' {
            current.push(ch);
        } else {
            if current.len() >= 2
                && current != "type"
                && current != "interface"
                && current != "export"
                && current != "Array"
            {
                tokens.insert(current.clone());
            }
            current.clear();
            if ch == '/' && ts_source.contains("//") {
                // Handled per line for comments
            }
        }
    }
    if current.len() >= 2 {
        tokens.insert(current);
    }
    tokens
}

fn strip_comments(src: &str) -> String {
    src.lines()
        .map(|l| l.split("//").next().unwrap_or(""))
        .collect::<Vec<_>>()
        .join("\n")
}

fn locate_bindings_target() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/bindings/src/generated.ts")
}

fn main() -> ExitCode {
    let check_only = env::args().any(|arg| arg == "--check");
    let target_path = locate_bindings_target();
    let decls = collect_ts_declarations();
    let rendered = render_generated_typescript(&decls);

    if check_only {
        let Ok(actual) = fs::read_to_string(&target_path) else {
            eprintln!("MISSING BINDINGS FILE: {}", target_path.display());
            return ExitCode::from(1);
        };
        if !actual.contains("export type DecimalValue = string;") {
            eprintln!("DRIFT DETECTED: DecimalValue string alias missing in generated.ts");
            return ExitCode::from(1);
        }

        let expected_tokens = extract_contract_tokens(&strip_comments(&rendered));
        let actual_tokens = extract_contract_tokens(&strip_comments(&actual));
        let missing: Vec<&String> = expected_tokens.difference(&actual_tokens).collect();

        if !missing.is_empty() {
            eprintln!(
                "CONTRACT DRIFT DETECTED in {}: missing Rust DTO symbols/fields: {:?}",
                target_path.display(),
                missing
            );
            return ExitCode::from(1);
        }
        println!(
            "OK: {} matches all {} Rust IPC contract symbols.",
            target_path.display(),
            expected_tokens.len()
        );
        ExitCode::SUCCESS
    } else {
        if let Some(parent) = target_path.parent() {
            if let Err(err) = fs::create_dir_all(parent) {
                eprintln!("Failed creating parent directory: {err}");
                return ExitCode::from(1);
            }
        }
        if let Err(err) = fs::write(&target_path, rendered) {
            eprintln!("Failed writing {}: {err}", target_path.display());
            return ExitCode::from(1);
        }
        println!("Exported TypeScript contracts to {}", target_path.display());
        ExitCode::SUCCESS
    }
}
