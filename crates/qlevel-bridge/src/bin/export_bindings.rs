//! Deterministic TypeScript IPC contract generator & CI drift checker (`--check`).
//!
//! Ensures `packages/bindings/src/generated.ts` stays 100% synchronized with `qlevel-domain`
//! and `qlevel-bridge` (`DecimalValue` exported strictly as `string`).

#![forbid(unsafe_code)]

use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::ExitCode;

use qlevel_bridge::dto::{
    AmbiguityDecisionInput, AmbiguityPromptPayload, AmbiguityResolutionChoice, BridgeErrorCode,
    BridgeErrorPayload, ConnectedAuthKindDto, DocumentRoleDto, ExportWorkbookInput,
    InputSourceKindDto, LevelingProgressEvent, LevelingSessionResultDto, PdfRasterRequestEvent,
    ProgressStageDto, ProviderAuthStatusDto, RenderedPageImageDto, SaveApiKeyInput,
    StagedInputDocumentDto, StartLevelingSessionInput, SubmitRenderedPdfPagesInput,
    TrapFindingSummaryDto, TriageClipboardInput, UpdateCheckStatusDto, VendorSummaryRowDto,
    WorkbookExportOutcomeDto,
};
use qlevel_domain::{
    AiConfig, AlignmentGroup, AlignmentResolution, AuthMethod, BoqItem, CellStatus,
    CommercialTerms, CurrencyCode, DetectedTrap, EffortLevel, GroupCardinality,
    LevelingSessionConfig, LineItemKind, Locale, MergedItemMode, ModelInfo, PeerPlugStrategy,
    PlugBasis, ProviderKind, SheetDirection, TrapCategory, TrapSeverity, VatMode, VatPolicy,
    WorkbookLayoutMode,
};
use ts_rs::TS;

fn render_generated_typescript() -> String {
    let mut blocks = vec![
        "// Auto-generated by `cargo run -p qlevel-bridge --bin export_bindings`. Do not edit manually.".to_owned(),
        "// Fixed-point rust_decimal values cross Tauri IPC strictly as base-10 strings.".to_owned(),
        "export type DecimalValue = string;".to_owned(),
    ];

    let decls = [
        CurrencyCode::decl(),
        Locale::decl(),
        SheetDirection::decl(),
        VatMode::decl(),
        VatPolicy::decl(),
        LineItemKind::decl(),
        BoqItem::decl(),
        CellStatus::decl(),
        CommercialTerms::decl(),
        GroupCardinality::decl(),
        MergedItemMode::decl(),
        AlignmentResolution::decl(),
        AlignmentGroup::decl(),
        TrapCategory::decl(),
        TrapSeverity::decl(),
        PlugBasis::decl(),
        DetectedTrap::decl(),
        ProviderKind::decl(),
        AuthMethod::decl(),
        EffortLevel::decl(),
        ModelInfo::decl(),
        AiConfig::decl(),
        WorkbookLayoutMode::decl(),
        PeerPlugStrategy::decl(),
        LevelingSessionConfig::decl(),
        ConnectedAuthKindDto::decl(),
        ProviderAuthStatusDto::decl(),
        SaveApiKeyInput::decl(),
        DocumentRoleDto::decl(),
        InputSourceKindDto::decl(),
        RenderedPageImageDto::decl(),
        StagedInputDocumentDto::decl(),
        TriageClipboardInput::decl(),
        SubmitRenderedPdfPagesInput::decl(),
        StartLevelingSessionInput::decl(),
        ProgressStageDto::decl(),
        LevelingProgressEvent::decl(),
        PdfRasterRequestEvent::decl(),
        AmbiguityResolutionChoice::decl(),
        AmbiguityPromptPayload::decl(),
        AmbiguityDecisionInput::decl(),
        VendorSummaryRowDto::decl(),
        TrapFindingSummaryDto::decl(),
        LevelingSessionResultDto::decl(),
        ExportWorkbookInput::decl(),
        WorkbookExportOutcomeDto::decl(),
        UpdateCheckStatusDto::decl(),
        BridgeErrorCode::decl(),
        BridgeErrorPayload::decl(),
    ];

    for decl in decls {
        let exported = if decl.starts_with("export ") {
            decl
        } else {
            format!("export {decl}")
        };
        blocks.push(exported);
    }

    let mut joined = blocks.join("\n\n");
    joined.push('\n');
    joined
}

fn locate_bindings_target() -> PathBuf {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    manifest_dir
        .join("../../packages/bindings/src/generated.ts")
}

fn main() -> ExitCode {
    let check_only = env::args().any(|arg| arg == "--check");
    let target_path = locate_bindings_target();
    let expected = render_generated_typescript();

    if check_only {
        match fs::read_to_string(&target_path) {
            Ok(actual) if actual == expected => {
                println!("OK: packages/bindings/src/generated.ts is up to date.");
                ExitCode::SUCCESS
            }
            Ok(_) => {
                eprintln!(
                    "DRIFT DETECTED: run `cargo run -p qlevel-bridge --bin export_bindings` to synchronize bindings."
                );
                ExitCode::from(1)
            }
            Err(err) => {
                eprintln!("MISSING BINDINGS FILE ({}): {err}", target_path.display());
                ExitCode::from(1)
            }
        }
    } else {
        if let Some(parent) = target_path.parent() {
            if let Err(err) = fs::create_dir_all(parent) {
                eprintln!("Failed creating parent directory: {err}");
                return ExitCode::from(1);
            }
        }
        if let Err(err) = fs::write(&target_path, expected) {
            eprintln!("Failed writing {}: {err}", target_path.display());
            return ExitCode::from(1);
        }
        println!("Exported TypeScript contracts to {}", target_path.display());
        ExitCode::SUCCESS
    }
}
